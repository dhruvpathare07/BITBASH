"""Generate the data file for the in-browser (offline) debug checker.

The browser must be able to check a player's fix with the network cut, but
it must not contain the corrected code (players could read it in devtools).
So for each correct line we store only a salted fingerprint of its
*normalized* form. The browser normalizes the player's line the same way,
fingerprints it, and compares. Same result as the server's line-by-line
check, without shipping the answers.

Run this whenever CORRECT_CODE / C_CORRECT_CODE change:

    python build_offline_checker.py

It writes frontend/bit-bash-New_frontend/src/data/offlineCheckerData.js
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from evaluator import CORRECT_CODE  # noqa: E402
from c_evaluator import C_CORRECT_CODE  # noqa: E402

OUT = os.path.join(
    HERE, "..", "frontend", "bit-bash-New_frontend", "src", "data", "offlineCheckerData.js"
)


def normalize(line: str) -> str:
    # Must match normalize() in evaluator.py / normalize_c() in c_evaluator.py
    # and normalizeLine() in src/utils/offlineChecker.js.
    line = line.lower()
    line = re.sub(r"\s+", "", line)
    line = re.sub(r"\b[a-z_][a-z0-9_]*\b", "var", line)
    return line


def fnv1a(data: bytes, seed: int) -> int:
    h = seed
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def fingerprint(salt: str, normalized: str) -> str:
    # Two FNV-1a passes with different seeds -> 64 bits, as hex.
    # Mirrored exactly in src/utils/offlineChecker.js.
    data = (salt + "|" + normalized).encode("utf-8")
    return f"{fnv1a(data, 0x811C9DC5):08x}{fnv1a(data, 0x01000193 ^ 0x5BD1E995):08x}"


def lines_of(code: str):
    return [ln.rstrip() for ln in code.strip().splitlines() if ln.strip()]


def build(refs: dict, language: str) -> dict:
    out = {}
    for topic, code in refs.items():
        out[topic] = [
            fingerprint(f"{language}|{topic}|{i}", normalize(line))
            for i, line in enumerate(lines_of(code))
        ]
    return out


def main():
    data = {"python": build(CORRECT_CODE, "python"), "c": build(C_CORRECT_CODE, "c")}
    body = json.dumps(data, indent=2, sort_keys=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by backend/build_offline_checker.py. Do not edit by hand.\n")
        f.write("// Salted fingerprints of each normalized correct line (no answers inside).\n")
        f.write(f"export const OFFLINE_CHECKER_DATA = {body};\n")
    total = sum(len(v) for lang in data.values() for v in lang.values())
    print(f"wrote {os.path.relpath(OUT, HERE)}: "
          f"{len(data['python'])} python + {len(data['c'])} c topics, {total} lines")


if __name__ == "__main__":
    main()
